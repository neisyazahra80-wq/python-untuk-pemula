# 1. String (teks)
nama_lengkap = "Neisya Khotimatul Zahra"

# 2. Integer (bilangan bulat)
semester = 3

# 3. Float (bilangan desimal)
ipk = 3.92

# 4. Boolean (logika benar/salah)
status_aktif = True

# Menampilkan nilai sekaligus mengecek tipe datanya dengan fungsi type()
print("Nama   :", nama_lengkap, "| Tipe:", type(nama_lengkap))
print("Semester:", semester, "| Tipe:", type(semester))
print("IPK    :", ipk, "| Tipe:", type(ipk))
print("Aktif  :", status_aktif, "| Tipe:", type(status_aktif))
